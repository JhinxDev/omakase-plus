"""Compare a running container against a git commit, read-only.

Only three read operations leave the workstation:

1. ``docker inspect`` for the live image id, revision label and compose chain.
2. one ``python -B`` call inside the container to locate the installed package.
3. one ``sha256sum`` pass over the installed package files.

Nothing is executed from the application package, no bytecode is written, and no
file, container or database is changed. The remote host is reached over ssh with
batch mode enabled.

Commands, from the repository root:

    python ops/release/check_drift.py
    python ops/release/check_drift.py --commit <sha> --all
    python ops/release/check_drift.py --json

Exit codes: 0 when the live container matches the commit, 1 when it has drifted,
2 when the check could not be completed.
"""

from __future__ import annotations

import argparse
import json
import shlex
import subprocess
import sys
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path

from build_image import (
    REPO_ROOT,
    ReleaseError,
    derive_revision,
    file_hashes,
    resolve_commit,
    tree_files,
)

STATUS_MATCH = "match"
STATUS_CONTENT = "content"
STATUS_MISSING = "missing"
STATUS_EXTRA = "extra"
# Bytecode is generated by the running interpreter, never shipped in the image.
RUNTIME_MARKERS = ("__pycache__",)
RUNTIME_SUFFIXES = (".pyc", ".pyo")
SSH_OPTIONS = ("-o", "BatchMode=yes", "-o", "ConnectTimeout=8")
DEFAULT_HOST = "omakase-ct"
DEFAULT_CONTAINER = "omakase-plus"

REMOTE_READER = """
import json, subprocess as sp, sys

container = sys.argv[1]


def capture(*args, timeout=180):
    return sp.check_output(args, text=True, timeout=timeout).strip()


details = json.loads(capture("docker", "inspect", container))[0]
image = details["Image"]
label = (details.get("Config", {}).get("Labels") or {}).get("org.opencontainers.image.revision")
chain = (details.get("Config", {}).get("Labels") or {}).get(
    "com.docker.compose.project.config_files"
)
locate = (
    "import importlib.util,pathlib;"
    "print(pathlib.Path(importlib.util.find_spec('omakase.plus').origin).parent)"
)
package = capture(
    "docker", "exec", "-e", "PYTHONDONTWRITEBYTECODE=1", container, "python", "-B", "-c", locate
)
hash_pass = 'cd "$1" && find . -type f -print0 | sort -z | xargs -0 sha256sum'
listing = capture("docker", "exec", container, "sh", "-c", hash_pass, "sh", package, timeout=180)
files = {}
for line in listing.splitlines():
    digest, separator, name = line.partition("  ")
    if not separator:
        continue
    files[name.removeprefix("./")] = digest
print(json.dumps({"image": image, "label": label, "package": package, "chain": chain, "files": files}))
"""


class DriftError(RuntimeError):
    """The drift comparison could not be completed."""


@dataclass(frozen=True)
class DriftRow:
    """One file compared between the commit tree and the live container."""

    status: str
    path: str
    expected: str | None
    observed: str | None


def is_runtime_artifact(path: str) -> bool:
    """Return True for interpreter bytecode, which the image never ships."""
    return path.endswith(RUNTIME_SUFFIXES) or any(marker in path for marker in RUNTIME_MARKERS)


def shipped_files(hashes: Mapping[str, str]) -> dict[str, str]:
    """Drop runtime bytecode from a hash map."""
    return {path: digest for path, digest in hashes.items() if not is_runtime_artifact(path)}


def compare_files(expected: Mapping[str, str], observed: Mapping[str, str]) -> list[DriftRow]:
    """Compare two hash maps into one row per path, sorted by path."""
    rows: list[DriftRow] = []
    for path in sorted(set(expected) | set(observed)):
        left = expected.get(path)
        right = observed.get(path)
        if left is None:
            status = STATUS_EXTRA
        elif right is None:
            status = STATUS_MISSING
        elif left != right:
            status = STATUS_CONTENT
        else:
            status = STATUS_MATCH
        rows.append(DriftRow(status=status, path=path, expected=left, observed=right))
    return rows


def drifted_rows(rows: Sequence[DriftRow]) -> list[DriftRow]:
    """Return only the rows that differ."""
    return [row for row in rows if row.status != STATUS_MATCH]


def drift_exit_code(rows: Sequence[DriftRow], *, label_matches: bool = True) -> int:
    """Return 0 only when every file and the revision label agree."""
    return 0 if label_matches and not drifted_rows(rows) else 1


def _short(digest: str | None) -> str:
    if digest is None:
        return "absent"
    return digest[:12]


def format_table(rows: Sequence[DriftRow], *, show_matches: bool = False) -> str:
    """Render the per-file drift table."""
    selected = list(rows) if show_matches else drifted_rows(rows)
    if not selected:
        return "no per-file differences"
    name_width = max(4, min(60, max(len(row.path) for row in selected)))
    lines = [f"{'STATUS':<8}  {'FILE':<{name_width}}  {'COMMIT':<12}  {'LIVE':<12}"]
    lines.append(f"{'-' * 8}  {'-' * name_width}  {'-' * 12}  {'-' * 12}")
    for row in selected:
        lines.append(
            f"{row.status:<8}  {row.path:<{name_width}}  "
            f"{_short(row.expected):<12}  {_short(row.observed):<12}"
        )
    return "\n".join(lines)


def summarize(rows: Sequence[DriftRow]) -> dict[str, int]:
    """Count rows by status."""
    counts = {STATUS_MATCH: 0, STATUS_CONTENT: 0, STATUS_MISSING: 0, STATUS_EXTRA: 0}
    for row in rows:
        counts[row.status] = counts.get(row.status, 0) + 1
    return counts


def read_live(host: str, container: str, timeout: int = 240) -> dict[str, object]:
    """Collect live state with read-only commands over ssh."""
    command = shlex.join(["python3", "-", container])
    try:
        result = subprocess.run(
            ["ssh", *SSH_OPTIONS, host, command],
            input=REMOTE_READER.encode("utf-8"),
            capture_output=True,
            timeout=timeout,
        )
    except FileNotFoundError as error:
        raise DriftError("ssh is not available on PATH") from error
    except subprocess.TimeoutExpired as error:
        raise DriftError(f"read-only ssh check timed out after {timeout}s") from error
    if result.returncode:
        detail = result.stderr.decode("utf-8", "replace").strip()
        raise DriftError(f"read-only collection failed on {host}:\n{detail[-3000:]}")
    try:
        live = json.loads(result.stdout)
    except ValueError as error:
        raise DriftError("read-only collection returned unreadable data") from error
    if not isinstance(live, dict) or not isinstance(live.get("files"), dict):
        raise DriftError("read-only collection returned an unexpected shape")
    return live


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Compare a running container against a git commit, read-only."
    )
    parser.add_argument("--repo", type=Path, default=REPO_ROOT, help="repository root")
    parser.add_argument("--commit", default="HEAD", help="commit or ref to compare against")
    parser.add_argument("--host", default=DEFAULT_HOST, help="ssh host alias")
    parser.add_argument("--container", default=DEFAULT_CONTAINER, help="container name")
    parser.add_argument("--manifest", type=Path, default=None, help="optional manifest to trust")
    parser.add_argument("--all", action="store_true", help="show matching files too")
    parser.add_argument("--json", action="store_true", help="print a JSON report instead")
    parser.add_argument("--timeout", type=int, default=240, help="ssh timeout in seconds")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    try:
        commit = resolve_commit(args.repo, args.commit)
        expected: dict[str, str] = shipped_files(file_hashes(tree_files(args.repo, commit)))
        if args.manifest is not None:
            manifest = json.loads(args.manifest.read_text(encoding="utf-8"))
            if manifest.get("git_commit") != commit:
                raise DriftError("manifest git_commit does not match the compared commit")
            if shipped_files(manifest.get("files", {})) != expected:
                raise DriftError("manifest file hashes do not match the commit tree")
        expected_revision = derive_revision(expected)
        live = read_live(args.host, args.container, args.timeout)
        raw_observed = live["files"]
        if not isinstance(raw_observed, dict):
            raise DriftError("live file map is unreadable")
        observed = shipped_files(raw_observed)
        ignored = len(raw_observed) - len(observed)
        label = live.get("label")
        label_matches = label == expected_revision
        rows = compare_files(expected, observed)
        code = drift_exit_code(rows, label_matches=label_matches)
        counts = summarize(rows)
        if args.json:
            print(
                json.dumps(
                    {
                        "git_commit": commit,
                        "expected_revision": expected_revision,
                        "live_revision": label,
                        "label_matches": label_matches,
                        "live_image": live.get("image"),
                        "live_package": live.get("package"),
                        "counts": counts,
                        "drifted": [
                            {
                                "status": row.status,
                                "path": row.path,
                                "commit_sha256": row.expected,
                                "live_sha256": row.observed,
                            }
                            for row in drifted_rows(rows)
                        ],
                    },
                    indent=2,
                )
            )
            return code
        print(f"commit              {commit}")
        print(f"package tree        src/omakase/plus ({len(expected)} files)")
        print(f"expected revision   {expected_revision}")
        print(f"live image          {live.get('image')}")
        print(f"live revision       {label}")
        print(f"live package path   {live.get('package')}")
        if ignored:
            print(f"runtime bytecode    {ignored} generated files ignored")
        print(f"access              read-only ssh {args.host} into container {args.container}")
        print()
        print(format_table(rows, show_matches=args.all))
        print()
        print(
            f"{counts[STATUS_CONTENT]} content, {counts[STATUS_MISSING]} missing, "
            f"{counts[STATUS_EXTRA]} unexpected, {counts[STATUS_MATCH]} matching"
        )
        if not label_matches:
            print(f"REVISION DRIFT: image label {label} is not {expected_revision}")
        if code:
            print("DRIFT DETECTED: the live container does not match the commit tree")
        else:
            print("IN SYNC: the live container matches the commit tree")
        return code
    except (ReleaseError, DriftError, OSError, ValueError) as error:
        print(f"drift check failed: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
