def test_playlists_declare_native_controls(tmp_path, provider):
    timeline = _timeline(provider)
    plan = _plan(tmp_path, timeline)
    streams = NativeStreams(tmp_path / "spool")

    class Track:
        name = "English"
        language = "eng"

    master = streams.master_playlist(plan, (Track(),)).decode()
    assert '#EXT-X-MEDIA:TYPE=AUDIO,GROUP-ID="aud"' in master
    assert '#EXT-X-MEDIA:TYPE=SUBTITLES,GROUP-ID="subs"' in master
    assert 'AUDIO="aud"' in master and 'SUBTITLES="subs"' in master
    assert "#EXT-X-STREAM-INF:BANDWIDTH=" in master
    assert "http" not in master and "real-debrid" not in master

    video = streams.video_playlist(plan).decode()
    assert "#EXT-X-PLAYLIST-TYPE:VOD" in video
    assert '#EXT-X-MAP:URI="init.mp4"' in video
    assert "#EXT-X-ENDLIST" in video
    extinf = [
        float(line.split(":")[1].rstrip(","))
        for line in video.splitlines()
        if line.startswith("#EXTINF:")
    ]
    target = int(
        next(
            line for line in video.splitlines() if line.startswith("#EXT-X-TARGETDURATION:")
        ).split(":")[1]
    )
    assert len(extinf) == len(timeline.segments)
    assert max(extinf) <= target

    audio = streams.audio_playlist(plan, timeline.audios[1].ordinal).decode()
    assert '#EXT-X-MAP:URI="init-a1.mp4"' in audio
    assert "a1-00000.m4s" in audio

    subtitles = streams.subtitle_playlist(plan, 0).decode()
    assert "s0-00000.vtt" in subtitles


