def _synthetic_init(timescale: int) -> bytes:
    mdhd = struct.pack(">B3xIIII", 0, 0, 0, timescale, 0)
    mdhd_box = struct.pack(">I", len(mdhd) + 8) + b"mdhd" + mdhd
    mdia = struct.pack(">I", len(mdhd_box) + 8) + b"mdia" + mdhd_box
    trak = struct.pack(">I", len(mdia) + 8) + b"trak" + mdia
    moov = struct.pack(">I", len(trak) + 8) + b"moov" + trak
    ftyp = struct.pack(">I", 12) + b"ftyp" + b"isom"
    return ftyp + moov


def _synthetic_fragment(base: int, timescale: int) -> bytes:
    tfdt = struct.pack(">B3xI", 0, base)
    tfdt_box = struct.pack(">I", len(tfdt) + 8) + b"tfdt" + tfdt
    traf = struct.pack(">I", len(tfdt_box) + 8) + b"traf" + tfdt_box
    moof = struct.pack(">I", len(traf) + 8) + b"moof" + traf
    return moof + struct.pack(">I", 8) + b"mdat"


