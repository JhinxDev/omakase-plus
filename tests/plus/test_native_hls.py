def test_a_window_starts_exactly_on_its_keyframe(tmp_path, provider, fixture_mkv):
    timeline = _timeline(provider)
    plan = _plan(tmp_path, timeline)
    streams = NativeStreams(tmp_path / "spool")
    streams.root.mkdir(parents=True, exist_ok=True)
    asyncio.run(streams.ensure(plan, 1))
    segment = plan.video_segment_path(1)
    assert segment.is_file()
    frames = _source_frame_hashes(fixture_mkv)
    boundary = timeline.segments[1][0] + timeline.origin
    expected_index = round(boundary * FRAME_RATE)
    joined = _with_init(
        tmp_path, "window1.mp4", (plan.root / "init.mp4").read_bytes(), segment.read_bytes()
    )
    produced = _frame_hash(joined)
    # The first produced frame is the source keyframe at the window boundary,
    # not the frame before it and not one from the previous window.
    assert produced == frames[expected_index]
    assert produced != frames[expected_index - 1]


def test_a_window_carries_its_declared_span_and_aligned_audio(tmp_path, provider):
    timeline = _timeline(provider)
    plan = _plan(tmp_path, timeline)
    streams = NativeStreams(tmp_path / "spool")
    streams.root.mkdir(parents=True, exist_ok=True)
    asyncio.run(streams.ensure(plan, 1))
    start, end = timeline.segments[1]
    video_init = (plan.root / "init.mp4").read_bytes()
    video = _packet_pts(
        _with_init(tmp_path, "v1.mp4", video_init, plan.video_segment_path(1).read_bytes())
    )
    # Decode times are absolute on the pass timeline, so the first frame sits at
    # the window start and the last frame at its declared end.
    assert start - 0.05 <= video[0] <= start + 0.2
    assert end - 0.4 <= video[-1] <= end + 0.2
    for audio in timeline.audios:
        audio_init = (plan.root / audio.init).read_bytes()
        track = _packet_pts(
            _with_init(
                tmp_path,
                f"a{audio.ordinal}.mp4",
                audio_init,
                plan.audio_segment_path(audio, 1).read_bytes(),
            ),
            "a:0",
        )
        assert start - 0.05 <= track[0] <= start + 0.2, audio.codec
        assert end - 0.4 <= track[-1] <= end + 0.2, audio.codec
        # Audio and video sit on the same window clock within one frame.
        assert abs(track[0] - video[0]) <= 0.06, audio.codec


def test_decode_times_place_each_segment_on_the_timeline(tmp_path, provider):
    timeline = _timeline(provider)
    plan = _plan(tmp_path, timeline)
    streams = NativeStreams(tmp_path / "spool")
    streams.root.mkdir(parents=True, exist_ok=True)
    asyncio.run(streams.ensure(plan, 2))
    init = (plan.root / "init.mp4").read_bytes()
    timescale = media_timescale(init)
    assert timescale
    expected = round(timeline.segments[2][0] * timescale)
    assert _tfdt_bases(plan.video_segment_path(2)) == [expected]
    for audio in timeline.audios:
        audio_init = (plan.root / audio.init).read_bytes()
        audio_timescale = media_timescale(audio_init)
        bases = _tfdt_bases(plan.audio_segment_path(audio, 2))
        assert bases == [round(timeline.segments[2][0] * audio_timescale)]
        # Both renditions declare the same moment, in their own timescale.
        assert abs(bases[0] / audio_timescale - expected / timescale) < 0.001


def test_subtitles_are_written_against_the_window_clock(tmp_path, provider):
    timeline = _timeline(provider)
    plan = _plan(tmp_path, timeline)
    streams = NativeStreams(tmp_path / "spool")
    streams.root.mkdir(parents=True, exist_ok=True)
    asyncio.run(streams.ensure(plan, 1, subtitles=1))
    text = plan.subtitle_segment_path(0, 1).read_text(encoding="utf-8")
    assert text.startswith("WEBVTT")
    # The fixture cue runs 7.25-9.00 s; window 1 starts at about 6.006 s.
    assert "Second line" in text
    start = timeline.segments[1][0] + timeline.origin
    cue = next(line for line in text.splitlines() if "-->" in line)
    first, _, last = cue.partition("-->")
    minutes, seconds = first.strip().split(":")
    local = int(minutes) * 60 + float(seconds)
    assert abs((start + local) - 7.25) < 0.1


