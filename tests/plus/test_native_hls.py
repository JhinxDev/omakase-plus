def _timeline(provider) -> NativeTimeline:
    timeline = asyncio.run(build_timeline(provider.url, DURATION))
    assert timeline is not None
    return timeline


def _plan(tmp_path, timeline) -> native_hls.NativePlan:
    plan = native_hls.NativePlan(
        key="plan", url=timeline.url, duration=timeline.duration, root=tmp_path / "plan"
    )
    plan.root.mkdir(parents=True, exist_ok=True)
    plan.timeline = timeline
    plan.ready.set()
    return plan


def _with_init(folder: Path, name: str, init: bytes, media: bytes) -> Path:
    """A media segment is only decodable together with its initialisation box."""
    path = folder / name
    path.write_bytes(init + media)
    return path


def _frame_hash(
    path: Path, *, select: int | None = None, source: Path | None = None, at: float | None = None
):
    """Hash one decoded frame, from a file or from a source time."""
    if source is not None:
        result = _run(
            FFMPEG,
            "-hide_banner",
            "-loglevel",
            "error",
            "-y",
            "-i",
            str(source),
            "-ss",
            f"{at:.3f}",
            "-frames:v",
            "1",
            "-f",
            "framemd5",
            "-",
        )
    else:
        result = _run(
            FFMPEG,
            "-hide_banner",
            "-loglevel",
            "error",
            "-y",
            "-i",
            str(path),
            "-map",
            "0:v:0",
            "-frames:v",
            "1",
            "-f",
            "framemd5",
            "-",
        )
    lines = [line for line in result.stdout.decode().splitlines() if not line.startswith("#")]
    digest = lines[-1].split(",")[-1].strip()
    return digest


def _source_frame_hashes(source: Path):
    """Every decoded frame hash in presentation order."""
    result = _run(
        FFMPEG,
        "-hide_banner",
        "-loglevel",
        "error",
        "-y",
        "-i",
        str(source),
        "-map",
        "0:v:0",
        "-f",
        "framemd5",
        "-",
    )
    return [
        line.split(",")[-1].strip()
        for line in result.stdout.decode().splitlines()
        if line.strip() and not line.startswith("#")
    ]


def _decode_hash_index(source: Path):
    return {digest: number for number, digest in enumerate(_source_frame_hashes(source))}


def _packet_pts(path: Path, stream="v:0"):
    result = _run(
        FFPROBE,
        "-v",
        "error",
        "-select_streams",
        stream,
        "-show_entries",
        "packet=pts_time",
        "-of",
        "csv=p=0",
        str(path),
    )
    values = []
    for line in result.stdout.decode().splitlines():
        try:
            values.append(float(line.strip().split(",")[0]))
        except ValueError:
            continue
    return sorted(values)


def _tfdt_bases(path_or_bytes):
    """Every fragment decode time in a media segment, in track timescale units."""
    if isinstance(path_or_bytes, Path):
        data = path_or_bytes.read_bytes()
    else:
        data = path_or_bytes
    bases = []
    for kind, _start, body, size in native_hls._boxes(data, 0, len(data)):
        if kind != b"moof":
            continue
        for kind2, _start2, body2, size2 in native_hls._boxes(data, body, body + size):
            if kind2 != b"traf":
                continue
            for kind3, _start3, body3, _size3 in native_hls._boxes(data, body2, body2 + size2):
                if kind3 != b"tfdt":
                    continue
                if data[body3] == 1:
                    bases.append(struct.unpack(">Q", data[body3 + 4 : body3 + 12])[0])
                else:
                    bases.append(struct.unpack(">I", data[body3 + 4 : body3 + 8])[0])
    return bases


