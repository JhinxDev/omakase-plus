def test_a_far_window_reads_only_that_window(tmp_path, provider):
    timeline = _timeline(provider)
    plan = _plan(tmp_path, timeline)
    streams = NativeStreams(tmp_path / "spool")
    streams.root.mkdir(parents=True, exist_ok=True)
    provider.requests.clear()
    asyncio.run(streams.ensure(plan, 4))
    assert plan.video_segment_path(4).is_file()
    total = 0
    for _method, header in provider.requests:
        if not header:
            continue
        start_text, _, end_text = header.partition("=")[2].partition("-")
        total += int(end_text) - int(start_text) + 1
    # A 30 s fixture is small, but the read must be a window, not the whole file.
    assert total < len(provider.payload) // 2
    assert not plan.video_segment_path(0).exists()
    assert not plan.video_segment_path(1).exists()


