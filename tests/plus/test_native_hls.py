class _RangeHandler(http.server.BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, *args):  # noqa: A003 - silence the default logger
        return

    def _target(self):
        return self.server.payload

    def _send(self, body: bytes, status: int, headers: dict | None = None, length=None):
        sent = dict(headers or {})
        sent.setdefault("Content-Length", str(len(body) if length is None else length))
        sent.setdefault("Content-Type", "application/octet-stream")
        self.send_response(status)
        for name, value in sent.items():
            self.send_header(name, value)
        self.end_headers()
        if self.command != "HEAD":
            self.wfile.write(body)

    def do_HEAD(self):  # noqa: N802 - http.server API
        self.server.requests.append(("HEAD", None))
        self._send(b"", 200, {"Accept-Ranges": "bytes"}, length=len(self._target()))

    def do_GET(self):  # noqa: N802 - http.server API
        data = self._target()
        header = self.headers.get("Range")
        mode = getattr(self.server, "mode", "ok")
        self.server.requests.append(("GET", header))
        if not header or mode == "ignore-range":
            # A provider that ignores Range answers with the whole file.
            self._send(data, 200)
            return
        unit, _, span = header.partition("=")
        if unit != "bytes" or "-" not in span:
            self._send(b"", 416)
            return
        start_text, _, end_text = span.partition("-")
        start = int(start_text or 0)
        end = int(end_text) if end_text else len(data) - 1
        if start >= len(data):
            self._send(b"", 416)
            return
        end = min(end, len(data) - 1)
        if mode == "wrong-range":
            # A 206 that claims to start at zero for every request.
            body = data[0 : end - start + 1]
            self._send(
                body,
                206,
                {"Content-Range": f"bytes 0-{len(body) - 1}/{len(data)}"},
            )
            return
        if mode == "oversized":
            body = data[start : min(len(data), end + 4096)]
            self._send(
                body,
                206,
                {"Content-Range": f"bytes {start}-{start + len(body) - 1}/{len(data)}"},
            )
            return
        if self.server.claim_full:
            self._send(
                b"",
                206,
                {
                    "Content-Range": f"bytes {start}-{end}/{len(data)}",
                    "Content-Length": str(end - start + 1),
                },
            )
            return
        if self.server.short_at:
            cut = self.server.short_at.pop(start, 0)
            if cut:
                part = data[start : max(start + 1, end + 1 - cut)]
                self._send(
                    part,
                    206,
                    {"Content-Range": f"bytes {start}-{start + len(part) - 1}/{len(data)}"},
                )
                return
        if mode == "truncated":
            body = data[start : start + max(1, (end - start) // 2)]
            self._send(
                b"",
                206,
                {
                    "Content-Range": f"bytes {start}-{end}/{len(data)}",
                    "Content-Length": str(end - start + 1),
                },
            )
            return
        body = data[start : end + 1]
        self._send(
            body,
            206,
            {"Content-Range": f"bytes {start}-{end}/{len(data)}", "Accept-Ranges": "bytes"},
        )


class _Provider:
    def __init__(self, payload: bytes):
        self.server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), _RangeHandler)
        self.server.payload = payload
        self.server.requests = []
        self.server.short_at = {}
        self.server.claim_full = False
        self.thread = threading.Thread(target=self.server.serve_forever, daemon=True)
        self.thread.start()

    @property
    def url(self):
        return f"http://127.0.0.1:{self.server.server_address[1]}/download/fixture.mkv"

    @property
    def requests(self):
        return self.server.requests

    @property
    def payload(self):
        return self.server.payload

    def close(self):
        self.server.shutdown()
        self.server.server_close()


