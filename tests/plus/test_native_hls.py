def test_timeline_follows_the_cue_index(provider):
    timeline = _timeline(provider)
    assert timeline.video_codec == "h264"
    assert [audio.codec for audio in timeline.audios] == ["aac", "ac3"]
    assert timeline.segments[0][0] == 0.0
    assert abs(timeline.segments[-1][1] - DURATION) < 0.2
    for (start, end), (next_start, _next_end) in zip(timeline.segments, timeline.segments[1:]):
        assert end == next_start
        assert 4.0 <= end - start <= 8.0
    assert len(timeline.clusters) == len(timeline.segments)
    # Boundaries are real keyframe times: the fixture forces one every six seconds.
    assert abs(timeline.segments[1][0] - SEGMENT_SECONDS) < 0.1


