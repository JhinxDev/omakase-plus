class ForYouLayoutError(ValueError):
    """Raised when a For You layout or refresh update is invalid."""


def _iso(moment: datetime) -> str:
    return moment.astimezone(UTC).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def _validate_kind(kind: str) -> str:
    if kind not in KINDS:
        raise ForYouLayoutError("Choose anime, movies, or tv")
    return kind


def default_layout(kind: str) -> list[dict[str, Any]]:
    _validate_kind(kind)
    return [{"id": entry["id"], "hidden": False} for entry in ROW_CATALOG[kind]]


def _entries(raw: Any) -> list[dict[str, Any]]:
    if isinstance(raw, str):
        if len(raw) > _FIELD_LIMIT:
            return []
        try:
            raw = json.loads(raw)
        except (ValueError, TypeError):
            return []
    if not isinstance(raw, list):
        return []
    return [item for item in raw if isinstance(item, dict)]


def normalize_layout(kind: str, raw: Any) -> list[dict[str, Any]]:
    _validate_kind(kind)
    catalog_ids = _ROWS_BY_KIND[kind]
    ordered: list[dict[str, Any]] = []
    seen: set[str] = set()
    for entry in _entries(raw):
        row_id = entry.get("id")
        if not isinstance(row_id, str) or row_id in seen or row_id not in catalog_ids:
            continue
        seen.add(row_id)
        ordered.append({"id": row_id, "hidden": bool(entry.get("hidden"))})
    for spec in ROW_CATALOG[kind]:
        if spec["id"] not in seen:
            seen.add(spec["id"])
            ordered.append({"id": spec["id"], "hidden": False})
    return ordered[:MAX_ROWS]


def load_layout(db, user_id: int, kind: str) -> dict[str, Any]:
    _validate_kind(kind)
    row = db.execute(
        "SELECT rows_json, revision, updated_at FROM viewer_discover_layout WHERE user_id=? AND kind=?",
        (user_id, kind),
    ).fetchone()
    if row is None:
        return {"rows": default_layout(kind), "revision": 0, "updated_at": "", "stored": False}
    return {
        "rows": normalize_layout(kind, row["rows_json"]),
        "revision": int(row["revision"]),
        "updated_at": str(row["updated_at"] or ""),
        "stored": True,
    }


def save_layout(
    db, user_id: int, kind: str, rows: Any, *, now: datetime | None = None
) -> dict[str, Any]:
    _validate_kind(kind)
    normalized = normalize_layout(kind, rows)
    if not normalized or all(entry["hidden"] for entry in normalized):
        raise ForYouLayoutError("Keep at least one For You shelf visible")
    stamp = _iso(now or datetime.now(UTC))
    db.execute(
        """INSERT INTO viewer_discover_layout(user_id, kind, rows_json, revision, updated_at)
           VALUES(?,?,?,1,?)
           ON CONFLICT(user_id, kind) DO UPDATE SET
             rows_json=excluded.rows_json,
             revision=viewer_discover_layout.revision+1,
             updated_at=excluded.updated_at""",
        (user_id, kind, json.dumps(normalized, separators=(",", ":")), stamp),
    )
    db.commit()
    return load_layout(db, user_id, kind)


def apply_layout_action(
    kind: str, current: list[dict[str, Any]], action: str, target: str
) -> list[dict[str, Any]]:
    _validate_kind(kind)
    if action == "reset":
        return default_layout(kind)
    rows = normalize_layout(kind, current)
    index = next((idx for idx, row in enumerate(rows) if row["id"] == target), None)
    if index is None:
        raise ForYouLayoutError("That For You shelf is not available")
    if action == "add":
        rows[index]["hidden"] = False
    elif action == "remove":
        rows[index]["hidden"] = True
    elif action == "move-up":
        if index == 0:
            raise ForYouLayoutError("That shelf is already first")
        rows[index - 1], rows[index] = rows[index], rows[index - 1]
    elif action == "move-down":
        if index == len(rows) - 1:
            raise ForYouLayoutError("That shelf is already last")
        rows[index + 1], rows[index] = rows[index], rows[index + 1]
    else:
        raise ForYouLayoutError("That For You edit is not supported")
    return rows


def edit_rows(kind: str, layout: list[dict[str, Any]]) -> list[dict[str, Any]]:
    _validate_kind(kind)
    catalog = _ROWS_BY_KIND[kind]
    view: list[dict[str, Any]] = []
    for index, entry in enumerate(normalize_layout(kind, layout)):
        spec = catalog[entry["id"]]
        view.append(
            {
                "id": entry["id"],
                "label": spec["label"],
                "description": spec["description"],
                "kind": kind,
                "hidden": bool(entry["hidden"]),
                "position": index + 1,
                "first": index == 0,
                "last": index == len(catalog) - 1,
            }
        )
    return view


def order_shelves(
    kind: str, layout: list[dict[str, Any]], shelves: list[dict[str, Any]]
) -> list[dict[str, Any]]:
    """Reorder and filter computed shelves according to the saved layout."""
    _validate_kind(kind)
    by_key = {row["key"]: row for row in shelves if row.get("cards")}
    ordered: list[dict[str, Any]] = []
    seen: set[str] = set()
    for entry in normalize_layout(kind, layout):
        row_id = entry["id"]
        seen.add(row_id)
        if entry["hidden"] or row_id not in by_key:
            continue
        ordered.append(by_key[row_id])
    for key, row in by_key.items():
        if key not in seen:
            ordered.append(row)
    return ordered


def taste_signal_hash(db, user_id: int) -> str:
    """Summarize viewing, rating, and feedback counts across all media kinds."""
    parts = []
    for sql in (
        "SELECT count(*), COALESCE(max(id), 0), COALESCE(max(last_observed_at), '') FROM watch_entries WHERE user_id=?",
        "SELECT count(*), COALESCE(max(id), 0) FROM watch_events WHERE user_id=? AND disposition='accepted'",
        "SELECT count(*), COALESCE(max(id), 0) FROM recommendation_feedback WHERE user_id=?",
        "SELECT count(*), COALESCE(max(updated_at), '') FROM movie_history WHERE user_id=?",
        "SELECT count(*), COALESCE(max(updated_at), '') FROM tv_history WHERE user_id=?",
    ):
        row = db.execute(sql, (user_id,)).fetchone()
        parts.append(":".join(str(item or "") for item in tuple(row)))
    return hashlib.sha256("|".join(parts).encode("utf-8")).hexdigest()[:24]


def load_refresh_settings(db, user_id: int) -> dict[str, Any]:
    row = db.execute(
        """SELECT auto_ai_refresh, cadence, last_signal_hash, last_refreshed_at, updated_at
           FROM discover_refresh_settings WHERE user_id=?""",
        (user_id,),
    ).fetchone()
    current_hash = taste_signal_hash(db, user_id)
    if row is None:
        return {
            "auto_ai_refresh": False,
            "cadence": "weekly",
            "last_signal_hash": "",
            "last_refreshed_at": "",
            "current_signal_hash": current_hash,
            "has_new_signals": False,
        }
    saved_hash = str(row["last_signal_hash"] or "")
    return {
        "auto_ai_refresh": bool(row["auto_ai_refresh"]),
        "cadence": str(row["cadence"] or "weekly"),
        "last_signal_hash": saved_hash,
        "last_refreshed_at": str(row["last_refreshed_at"] or ""),
        "current_signal_hash": current_hash,
        "has_new_signals": bool(saved_hash and saved_hash != current_hash),
    }


def save_refresh_settings(
    db,
    user_id: int,
    *,
    auto_ai_refresh: bool,
    cadence: str,
    now: datetime | None = None,
) -> dict[str, Any]:
    if cadence not in CADENCES:
        raise ForYouLayoutError("Choose a supported refresh schedule")
    stamp = _iso(now or datetime.now(UTC))
    sig = taste_signal_hash(db, user_id)
    db.execute(
        """INSERT INTO discover_refresh_settings
             (user_id, auto_ai_refresh, cadence, last_signal_hash, updated_at)
           VALUES (?,?,?,?,?)
           ON CONFLICT(user_id) DO UPDATE SET
             auto_ai_refresh=excluded.auto_ai_refresh,
             cadence=excluded.cadence,
             last_signal_hash=CASE
               WHEN discover_refresh_settings.last_signal_hash='' THEN excluded.last_signal_hash
               ELSE discover_refresh_settings.last_signal_hash
             END,
             updated_at=excluded.updated_at""",
        (user_id, 1 if auto_ai_refresh and cadence != "manual" else 0, cadence, sig, stamp),
    )
    db.commit()
    return load_refresh_settings(db, user_id)


def mark_ai_refreshed(db, user_id: int, *, now: datetime | None = None) -> None:
    stamp = _iso(now or datetime.now(UTC))
    sig = taste_signal_hash(db, user_id)
    db.execute(
        """INSERT INTO discover_refresh_settings
             (user_id, auto_ai_refresh, cadence, last_signal_hash, last_refreshed_at, updated_at)
           VALUES (?, 0, 'weekly', ?, ?, ?)
           ON CONFLICT(user_id) DO UPDATE SET
             last_signal_hash=excluded.last_signal_hash,
             last_refreshed_at=excluded.last_refreshed_at,
             updated_at=excluded.updated_at""",
        (user_id, sig, stamp, stamp),
    )
    db.commit()


def is_ai_refresh_due(db, user_id: int, *, now: datetime | None = None) -> bool:
    settings = load_refresh_settings(db, user_id)
    if not settings["auto_ai_refresh"] or settings["cadence"] == "manual":
        return False
    if settings["cadence"] == "on_new_data":
        return settings["has_new_signals"] or not settings["last_refreshed_at"]
    last_raw = settings["last_refreshed_at"]
    if not last_raw:
        return True
    try:
        last_dt = datetime.fromisoformat(last_raw.replace("Z", "+00:00"))
    except ValueError:
        return True
    return (now or datetime.now(UTC)) - last_dt >= timedelta(days=7)
